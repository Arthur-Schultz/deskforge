#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE ROLE ${DATABASE_USERNAME} LOGIN PASSWORD '${DATABASE_PASSWORD}';
    GRANT CONNECT ON DATABASE ${POSTGRES_DB} TO ${DATABASE_USERNAME};
    GRANT USAGE ON SCHEMA public TO ${DATABASE_USERNAME};
    ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
        GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${DATABASE_USERNAME};
    ALTER DEFAULT PRIVILEGES FOR ROLE ${POSTGRES_USER} IN SCHEMA public
        GRANT USAGE, SELECT ON SEQUENCES TO ${DATABASE_USERNAME};
EOSQL
